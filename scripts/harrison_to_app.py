#!/usr/bin/env python3
"""Convert Harrison study outputs (study/questions, study/anki) into app topic data.

Writes src/data/29-harrison.js declaring `const HARRISON_TOPICS = [...]`, one topic per
finished chapter. Each topic carries a `chapter` field (an existing app chapter such as
'Cardiology', or 'General Medicine'); shell.html keeps it when appending to TOPICS.

Re-run after each daily session:  python3 scripts/harrison_to_app.py && npm run check
Content is not rewritten here: question text, options, and explanations are copied
verbatim from the study files, which were themselves written from the source chapter.
"""
import csv, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QDIR, ADIR, NDIR = ROOT / "study/questions", ROOT / "study/anki", ROOT / "study/notes"
OUT = ROOT / "src/data/29-harrison.js"

# Harrison chapter number -> app chapter. Anything unlisted goes to General Medicine.
CHAPTER_MAP = {
    15: "Cardiology",
    16: "Gastroenterology",
    17: "Neurology", 23: "Neurology", 24: "Neurology", 29: "Neurology", 31: "Neurology",
    39: "Pulmonology", 40: "Pulmonology", 41: "Pulmonology", 43: "Cardiology", 44: "Cardiology",
    47: "Gastroenterology", 49: "Gastroenterology", 51: "Gastroenterology",
    20: "Infectious Diseases", 21: "Infectious Diseases", 22: "Infectious Diseases",
}
DEFAULT_CHAPTER = "General Medicine"

Q_RE = re.compile(r"^\*\*(\d+)\.\*\*\s*(.*)")
OPT_RE = re.compile(r"^([A-E])\.\s+(.*)")
ANS_RE = re.compile(r"^\*\*(\d+)\.\s*([A-E])\*\*\s*[—-]\s*(.*)")


def parse_questions(path):
    text = path.read_text()
    if "## Answers" not in text:
        sys.exit(f"{path}: no '## Answers' section")
    body, answers = text.split("## Answers", 1)

    qs, cur = {}, None
    for line in body.splitlines():
        line = line.strip()
        m = Q_RE.match(line)
        if m:
            cur = int(m.group(1))
            qs[cur] = {"q": m.group(2).strip(), "options": []}
            continue
        if cur is None or not line:
            continue
        m = OPT_RE.match(line)
        if m:
            qs[cur]["options"].append(m.group(2).strip())
        elif not qs[cur]["options"]:
            qs[cur]["q"] += " " + line  # multi-line stem

    ans, cur = {}, None
    for line in answers.splitlines():
        line = line.strip()
        m = ANS_RE.match(line)
        if m:
            cur = int(m.group(1))
            ans[cur] = {"letter": m.group(2), "main": m.group(3).strip(), "wrong": [], "src": ""}
            continue
        if cur is None or not line:
            continue
        if line.startswith("Source:"):
            ans[cur]["src"] = line
        elif line.startswith("- "):
            ans[cur]["wrong"].append(line[2:].strip())
        else:
            ans[cur]["main"] += " " + line

    items = []
    for n in sorted(qs):
        q, a = qs[n], ans.get(n)
        if a is None:
            sys.exit(f"{path}: question {n} has no answer")
        if len(q["options"]) != 5:
            sys.exit(f"{path}: question {n} has {len(q['options'])} options")
        explain = " ".join([a["main"]] + [f"({w})" for w in a["wrong"]] + ([a["src"]] if a["src"] else []))
        items.append({"q": q["q"], "options": q["options"], "answer": "ABCDE".index(a["letter"]), "explain": explain})
    if set(ans) - set(qs):
        sys.exit(f"{path}: answers without questions: {sorted(set(ans) - set(qs))}")
    return items


def parse_cards(path):
    with path.open(newline="") as f:
        rows = list(csv.DictReader(f))
    return [{"front": r["Front"].strip(), "back": r["Back"].strip()} for r in rows if r.get("Front")]


def chapter_title(num):
    p = NDIR / f"ch_{num:04d}.md"
    first = p.read_text().splitlines()[0] if p.exists() else ""
    m = re.match(r"#\s*Ch\s*\d+\s*[—-]\s*(.+?)(\s*\(.*\))?$", first)
    return m.group(1).strip() if m else f"Chapter {num}"


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main():
    topics = []
    for qp in sorted(QDIR.glob("ch_*.md")):
        num = int(qp.stem.split("_")[1])
        ap = ADIR / f"ch_{num:04d}.csv"
        if not ap.exists():
            sys.exit(f"missing {ap}")
        title = chapter_title(num)
        topics.append({
            "id": f"harrison-ch{num:04d}-{slug(title)}",
            "name": f"{title} (Harrison Ch {num})",
            "blurb": f"Step 2 CK review of Harrison's 22e Chapter {num}: {title}.",
            "chapter": CHAPTER_MAP.get(num, DEFAULT_CHAPTER),
            "flashcards": parse_cards(ap),
            "quiz": parse_questions(qp),
        })

    lines = [
        "// Harrison's Principles of Internal Medicine, 22e — Step 2 CK review, one topic per chapter.",
        "// GENERATED by scripts/harrison_to_app.py from study/questions and study/anki — do not hand-edit;",
        "// fix the study files and re-run. Each topic's `chapter` field is kept by shell.html.",
        "const HARRISON_TOPICS = [",
    ]
    for t in topics:
        lines.append(json.dumps(t, ensure_ascii=False, indent=1) + ",")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    nq = sum(len(t["quiz"]) for t in topics)
    nc = sum(len(t["flashcards"]) for t in topics)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(topics)} topics, {nq} questions, {nc} flashcards")
    for t in topics:
        dist = [sum(1 for q in t["quiz"] if q["answer"] == i) for i in range(5)]
        print(f"  {t['id']} [{t['chapter']}] q={len(t['quiz'])} cards={len(t['flashcards'])} answer A-E={dist}")


if __name__ == "__main__":
    main()
